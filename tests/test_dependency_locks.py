"""Every dependency install in CI and in the images is hash-locked.

The locks are generated by ``uv pip compile --generate-hashes`` from the
``*.in`` file named in each lock's header; this suite checks their shape and
that every installer uses them. It does not re-resolve the locks.
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WORKFLOWS = sorted((ROOT / ".github" / "workflows").glob("*.yml"))
DOCKERFILES = sorted(
    path for path in ROOT.rglob("Dockerfile*") if ".git" not in path.parts and path.is_file()
)
LOCKS = [ROOT / "requirements.txt", ROOT / "requirements-test.txt",
         *sorted((ROOT / "requirements" / "ci").glob("*.txt"))]
PIP_INSTALL = re.compile(r"pip\s+install\b[^\n]*")
PIN = re.compile(r"(?m)^([A-Za-z0-9][A-Za-z0-9._-]*)(?:\[[^\]]*\])?==([^\s;\\]+)")
LOCK_LINE = re.compile(r"^[a-z0-9][a-z0-9.-]*==[^\s;\\]+( ; [^\\]+)? \\$")


def _name(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _pins(path: Path) -> dict[str, str]:
    text = path.read_text(encoding="utf-8")
    return {_name(match.group(1)): match.group(2) for match in PIN.finditer(text)}


def test_every_pip_install_requires_hashes_from_a_committed_lock():
    lock_names = {path.relative_to(ROOT).as_posix() for path in LOCKS}
    seen = 0
    for path in [*WORKFLOWS, *DOCKERFILES]:
        for command in PIP_INSTALL.findall(path.read_text(encoding="utf-8")):
            seen += 1
            words = command.replace('"', " ").replace("'", " ").rstrip("\\ ").split()
            assert "--require-hashes" in words, (path.name, command)
            files = {words[i + 1] for i, word in enumerate(words[:-1])
                     if word in {"-r", "--requirement"}}
            assert files and files <= lock_names, (path.name, command)
            operands = [word for i, word in enumerate(words[2:], 2)
                        if not word.startswith("-") and words[i - 1] not in {"-r", "--requirement"}]
            assert operands == [], (path.name, command)
    assert seen >= 11


def test_every_lock_pins_and_hashes_every_requirement():
    for path in LOCKS:
        lines = path.read_text(encoding="utf-8").splitlines()
        assert lines[0] == "# This file was autogenerated by uv via the following command:", path
        source = path.with_suffix(".in")
        assert source.is_file(), source
        assert "--generate-hashes" in lines[1] and source.name in lines[1], (path, lines[1])
        requirements = [i for i, line in enumerate(lines) if line and not line[0].isspace()
                        and not line.startswith("#")]
        assert requirements, path
        for index in requirements:
            assert LOCK_LINE.match(lines[index]), (path.name, lines[index])
            assert re.fullmatch(r" {4}--hash=sha256:[0-9a-f]{64}( \\)?", lines[index + 1]), (
                path.name, lines[index])


def test_top_level_pins_and_shared_packages_agree_across_locks():
    runtime = _pins(ROOT / "requirements.txt")
    top_level = _pins(ROOT / "requirements.in")
    assert set(top_level) == {"fastapi", "uvicorn", "pydantic", "httpx"}
    for name, version in top_level.items():
        assert runtime[name] == version, name
    test = _pins(ROOT / "requirements-test.txt")
    assert "pytest" in test
    for name in runtime.keys() & test.keys():
        assert runtime[name] == test[name], name
    for path in sorted((ROOT / "requirements" / "ci").glob("*.in")):
        locked = _pins(path.with_suffix(".txt"))
        pinned = _pins(path)
        assert pinned, path
        for name, version in pinned.items():
            assert locked[name] == version, (path.name, name)


def test_browser_runner_installs_only_from_its_lockfile():
    workflow = (ROOT / ".github" / "workflows" / "responsive-ui.yml").read_text(encoding="utf-8")
    assert not re.search(r"npm\s+(install|i)\b", workflow)
    assert 'npm ci --prefix "$RUNNER_TEMP/responsive-browser"' in workflow
    runner = ROOT / "tools" / "responsive-browser"
    manifest = json.loads((runner / "package.json").read_text(encoding="utf-8"))
    lock = json.loads((runner / "package-lock.json").read_text(encoding="utf-8"))
    wanted = manifest["devDependencies"]["playwright"]
    assert re.fullmatch(r"\d+\.\d+\.\d+", wanted)
    assert lock["packages"][""]["devDependencies"] == manifest["devDependencies"]
    assert lock["packages"]["node_modules/playwright"]["version"] == wanted
    for name, entry in lock["packages"].items():
        if name:
            assert entry["integrity"].startswith("sha512-"), name
            assert entry["resolved"].startswith("https://registry.npmjs.org/"), name
